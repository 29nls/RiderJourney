import { ServiceUnavailableException } from '@nestjs/common';
import {
  DeleteObjectCommand,
  GetObjectCommand,
  HeadObjectCommand,
  PutObjectCommand,
  S3Client,
} from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import type { AppConfig } from '../config/env.js';

export type ObjectHead = {
  contentLength: number;
  contentType: string | null;
  etag: string | null;
};

export type ObjectStream = {
  stream: AsyncIterable<Uint8Array>;
  contentLength: number | null;
};

/**
 * The only surface the rest of the backend may use for object storage. Keys
 * are always generated by the server, never accepted from a client.
 */
export interface ObjectStorage {
  presignPut(key: string, contentType: string, expiresInSeconds: number): Promise<string>;
  presignGet(key: string, expiresInSeconds: number): Promise<string>;
  head(key: string): Promise<ObjectHead | null>;
  openRead(key: string): Promise<ObjectStream>;
  delete(key: string): Promise<void>;
}

export const OBJECT_STORAGE = Symbol('OBJECT_STORAGE');

class UnavailableObjectStorage implements ObjectStorage {
  private fail(): never {
    throw new ServiceUnavailableException({
      code: 'MEDIA_UNAVAILABLE',
      title: 'Penyimpanan media belum dikonfigurasi',
      detail: 'MEDIA_S3_BUCKET, MEDIA_S3_ACCESS_KEY, dan MEDIA_S3_SECRET_KEY harus diisi.',
    });
  }
  presignPut(): Promise<string> {
    return Promise.resolve(this.fail());
  }
  presignGet(): Promise<string> {
    return Promise.resolve(this.fail());
  }
  head(): Promise<ObjectHead | null> {
    return Promise.resolve(this.fail());
  }
  openRead(): Promise<ObjectStream> {
    return Promise.resolve(this.fail());
  }
  delete(): Promise<void> {
    return Promise.resolve(this.fail());
  }
}

export class S3ObjectStorage implements ObjectStorage {
  private readonly client: S3Client;
  constructor(private readonly bucket: string, config: AppConfig) {
    this.client = new S3Client({
      endpoint: config.mediaS3Endpoint || undefined,
      region: config.mediaS3Region || 'us-east-1',
      forcePathStyle: config.mediaS3ForcePathStyle,
      credentials: {
        accessKeyId: config.mediaS3AccessKey,
        secretAccessKey: config.mediaS3SecretKey,
      },
      // The SDK otherwise attaches flexible-checksum parameters to presigned
      // PUTs, which S3-compatible servers reject as a bad digest. Integrity is
      // verified server-side after the upload instead.
      requestChecksumCalculation: 'WHEN_REQUIRED',
      responseChecksumValidation: 'WHEN_REQUIRED',
    });
  }

  async presignPut(key: string, contentType: string, expiresInSeconds: number): Promise<string> {
    return getSignedUrl(
      this.client,
      new PutObjectCommand({
        Bucket: this.bucket,
        Key: key,
        ContentType: contentType,
        // A finished object cannot be replaced through a replayed upload URL.
        IfNoneMatch: '*',
      }),
      {
        expiresIn: expiresInSeconds,
        // Sign the headers the uploader must send, so a different type or a
        // second PUT over the same key fails at the storage signature.
        signableHeaders: new Set(['content-type', 'if-none-match']),
      },
    );
  }

  async presignGet(key: string, expiresInSeconds: number): Promise<string> {
    return getSignedUrl(this.client, new GetObjectCommand({ Bucket: this.bucket, Key: key }), {
      expiresIn: expiresInSeconds,
    });
  }

  async head(key: string): Promise<ObjectHead | null> {
    try {
      const result = await this.client.send(new HeadObjectCommand({ Bucket: this.bucket, Key: key }));
      return {
        contentLength: result.ContentLength ?? -1,
        contentType: result.ContentType ?? null,
        etag: result.ETag ?? null,
      };
    } catch (error) {
      const status = (error as { $metadata?: { httpStatusCode?: number } }).$metadata?.httpStatusCode;
      const name = (error as { name?: string }).name;
      if (status === 404 || name === 'NotFound' || name === 'NoSuchKey') return null;
      throw error;
    }
  }

  async openRead(key: string): Promise<ObjectStream> {
    const result = await this.client.send(new GetObjectCommand({ Bucket: this.bucket, Key: key }));
    if (!result.Body) throw new Error('storage returned no body');
    return {
      stream: result.Body as unknown as AsyncIterable<Uint8Array>,
      contentLength: result.ContentLength ?? null,
    };
  }

  async delete(key: string): Promise<void> {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.bucket, Key: key }));
  }
}

export function createObjectStorage(config: AppConfig): ObjectStorage {
  if (!config.mediaS3Bucket || !config.mediaS3AccessKey || !config.mediaS3SecretKey) {
    return new UnavailableObjectStorage();
  }
  return new S3ObjectStorage(config.mediaS3Bucket, config);
}
